const dictionaries: Record<Language, Record<TKey, string>> = { en, zh }

export function resolveLanguage(preference: LanguagePreference | undefined): Language {
  if (preference === 'zh') return 'zh'
  if (preference === 'en') return 'en'
  const system = typeof navigator !== 'undefined' ? navigator.language : 'en'
  return system.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export function localeFor(language: Language): string {
  return language === 'zh' ? 'zh-CN' : 'en-US'
}

export function translate(
  language: Language,
  key: TKey,
  vars?: Record<string, string | number>,
): string {
  const template = dictionaries[language][key] ?? en[key]
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_match, name: string) =>
    vars[name] !== undefined ? String(vars[name]) : `{${name}}`,
  )
}

